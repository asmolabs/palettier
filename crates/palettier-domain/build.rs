use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let catalog_dir = manifest_dir
        .join("catalog")
        .canonicalize()
        .expect("Catalog directory not found in crates/palettier-domain/catalog");

    let pigments_path = catalog_dir.join("pigments.csv");
    let brands_dir = catalog_dir.join("brands");

    println!("cargo:rerun-if-changed={}", pigments_path.display());
    println!("cargo:rerun-if-changed={}", brands_dir.display());

    let mut brand_files: Vec<PathBuf> = fs::read_dir(&brands_dir)
        .expect("Failed to read catalog/brands")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.is_file() && p.extension().and_then(|s| s.to_str()) == Some("csv"))
        .collect();
    brand_files.sort_by(|a, b| a.file_name().cmp(&b.file_name()));

    assert!(
        !brand_files.is_empty(),
        "No brand files found in {}",
        brands_dir.display()
    );

    let mut code = String::new();
    code.push_str("// File generated by build.rs — do not edit by hand.\n");
    code.push_str(&format!(
        "pub const PIGMENTS_CSV: &str = include_str!({:?});\n\n",
        pigments_path.to_str().expect("UTF-8 path expected")
    ));
    code.push_str("pub const BRAND_FILES: &[(&str, &str)] = &[\n");
    for brand in &brand_files {
        println!("cargo:rerun-if-changed={}", brand.display());
        let name = brand
            .file_name()
            .and_then(|s| s.to_str())
            .expect("UTF-8 filename expected");
        let path_str = brand.to_str().expect("UTF-8 path expected");
        code.push_str(&format!("    ({:?}, include_str!({:?})),\n", name, path_str));
    }
    code.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("catalog_files.rs"), code).expect("Failed to write catalog_files.rs");
}
